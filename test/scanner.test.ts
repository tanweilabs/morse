import { mkdirSync, mkdtempSync, rmSync, utimesSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createClaudeAdapter } from '../src/adapters/claude.js';
import { createCodexAdapter } from '../src/adapters/codex.js';
import type { AgentAdapter, SessionInfo } from '../src/adapters/types.js';
import { listAllSessions } from '../src/directory/scanner.js';

// Session stores written here, as Claude Code and Codex lay them out — nothing is read from the real home.
const root = mkdtempSync(join(tmpdir(), 'morse-scan-'));
afterAll(() => rmSync(root, { recursive: true, force: true }));

/** Write JSON lines to a file under the store root, with a fixed modification time. */
function jsonl(rel: string, lines: unknown[], mtime = new Date('2026-03-01T08:00:00Z')): void {
  const path = join(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, lines.map((l) => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n');
  utimesSync(path, mtime, mtime);
}

const userSays = (cwd: string, content: unknown) => ({ type: 'user', cwd, message: { role: 'user', content } });
const meta = (payload: Record<string, unknown>) => ({ type: 'session_meta', payload });

const CLAUDE = {
  named: '0a0a0a0a-0000-4000-8000-00000000000a',
  untitled: '0b0b0b0b-0000-4000-8000-00000000000b',
  partsOnly: '0c0c0c0c-0000-4000-8000-00000000000c',
};
const CODEX = {
  indexed: '1a1a1a1a-0000-4000-8000-00000000001a',
  notIndexed: '1b1b1b1b-0000-4000-8000-00000000001b',
  child: '1c1c1c1c-0000-4000-8000-00000000001c',
  split: '1d1d1d1d-0000-4000-8000-00000000001d',
  brokenTail: '1e1e1e1e-0000-4000-8000-00000000001e',
  gone: '1f1f1f1f-0000-4000-8000-00000000001f',
};

beforeAll(() => {
  // Claude: ~/.claude/projects/<escaped dir>/<session id>.jsonl — the folder name is NOT the real directory
  jsonl(`claude/-x-escaped-one/${CLAUDE.named}.jsonl`, [
    userSays('/work/ledger', 'draft the invoice export'),
    { type: 'custom-title', customTitle: 'first name' },
    { type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text: 'ok' }] } },
    { type: 'custom-title', customTitle: 'Invoice export' },
  ]);
  jsonl(`claude/-x-escaped-two/${CLAUDE.untitled}.jsonl`, [
    userSays('/work/notes', '<local-command-caveat>Caveat: generated by a local command</local-command-caveat>'),
    userSays('/work/notes', '  why does the cache miss?  '),
  ]);
  jsonl(`claude/-x-escaped-two/${CLAUDE.partsOnly}.jsonl`, [userSays('/work/parts', [{ type: 'image' }, { type: 'text', text: '<system-reminder>x' }, { type: 'text', text: 'rename the CLI flags' }])]);
  jsonl('claude/-x-escaped-two/not-a-session-id.jsonl', [userSays('/work/x', 'ignored')]);
  jsonl(`claude/memory/${'0d0d0d0d-0000-4000-8000-00000000000d'}.txt`, ['not jsonl']);

  // Codex: ~/.codex/sessions/YYYY/MM/DD/rollout-<time>-<thread id>.jsonl, titles in session_index.jsonl
  jsonl(`codex/2026/02/10/rollout-2026-02-10T09-00-00-${CODEX.indexed}.jsonl`, [meta({ cwd: '/work/site', cli_version: '0.150.0', originator: 'codex_cli_rs' }), { type: 'turn_context' }], new Date('2026-02-20T00:00:00Z'));
  jsonl(`codex/2026/02/10/rollout-2026-02-10T10-00-00-${CODEX.notIndexed}.jsonl`, [meta({ cwd: '/work/orphaned-repo' })]);
  jsonl(`codex/2026/02/10/rollout-2026-02-10T11-00-00-${CODEX.child}.jsonl`, [meta({ cwd: '/work/site', thread_source: 'subagent', parent_thread_id: CODEX.indexed })]);
  jsonl(`codex/2026/02/10/rollout-2026-02-10T12-00-00-${CODEX.split}.jsonl`, [meta({ cwd: '/work/old-place' })]);
  jsonl(`codex/2026/02/11/rollout-2026-02-11T08-00-00-${CODEX.split}.jsonl`, [meta({ cwd: '/work/new-place' })]);
  jsonl(`codex/2026/02/10/rollout-2026-02-10T13-00-00-${CODEX.brokenTail}.jsonl`, [meta({ cwd: '/work/b' })]);
  jsonl(`codex/2026/02/12/rollout-2026-02-12T13-00-00-${CODEX.brokenTail}.jsonl`, [{ type: 'compacted' }]);
  jsonl('codex-index.jsonl', [
    { id: CODEX.indexed, thread_name: 'Site redesign', updated_at: '2026-02-11T00:00:00.000Z' },
    { id: CODEX.gone, thread_name: 'rollout deleted', updated_at: '2026-02-01T00:00:00.000Z' },
  ]);
});

const byId = (sessions: SessionInfo[], id: string) => sessions.find((s) => s.sessionId === id);

describe('Claude sessions (~/.claude/projects)', () => {
  const claude = () => createClaudeAdapter({ projectsDir: join(root, 'claude') }).listSessions();

  it('one per session file named by a session id — other files and folders are not sessions', async () => {
    expect((await claude()).map((s) => s.sessionId).sort()).toEqual(Object.values(CLAUDE).sort());
  });

  it('the directory comes from the transcript, not from the escaped folder name', async () => {
    const s = byId(await claude(), CLAUDE.named);
    expect(s).toMatchObject({ agent: 'claude', cwd: '/work/ledger' });
  });

  it('title: the last custom title, else the first user text a person wrote (wrapped system turns skipped)', async () => {
    const sessions = await claude();
    expect(byId(sessions, CLAUDE.named)?.title).toBe('Invoice export');
    expect(byId(sessions, CLAUDE.untitled)?.title).toBe('why does the cache miss?');
    expect(byId(sessions, CLAUDE.partsOnly)?.title).toBe('rename the CLI flags');
  });

  it('last activity: the time the file was last written', async () => {
    expect(byId(await claude(), CLAUDE.named)?.lastActiveAt).toBe(Date.parse('2026-03-01T08:00:00Z'));
  });
});

describe('Codex sessions (~/.codex/sessions + session_index.jsonl)', () => {
  const codex = () => createCodexAdapter({ sessionsDir: join(root, 'codex'), indexFile: join(root, 'codex-index.jsonl') }).listSessions();

  it('only threads that can take a message: no sub-agent threads, no thread whose newest rollout has no session_meta, no index entry without a rollout', async () => {
    expect((await codex()).map((s) => s.sessionId).sort()).toEqual([CODEX.indexed, CODEX.notIndexed, CODEX.split].sort());
  });

  it('title from the index, else the last part of the directory; the directory from session_meta', async () => {
    const sessions = await codex();
    expect(byId(sessions, CODEX.indexed)).toMatchObject({ agent: 'codex', title: 'Site redesign', cwd: '/work/site' });
    expect(byId(sessions, CODEX.notIndexed)?.title).toBe('orphaned-repo');
  });

  it('a thread in several rollouts appears once, as its newest rollout says', async () => {
    const split = (await codex()).filter((s) => s.sessionId === CODEX.split);
    expect(split).toHaveLength(1);
    expect(split[0]?.cwd).toBe('/work/new-place');
  });

  it('last activity: the later of the index time and the rollout file time (the index goes stale)', async () => {
    expect(byId(await codex(), CODEX.indexed)?.lastActiveAt).toBe(Date.parse('2026-02-20T00:00:00Z'));
  });
});

describe('listAllSessions: the directory over every adapter', () => {
  const fixed = (agent: string, sessions: Array<[string, number]>): AgentAdapter => ({
    agent,
    listSessions: async () => sessions.map(([sessionId, lastActiveAt]) => ({ agent, sessionId, title: sessionId, cwd: '', lastActiveAt })),
  });

  it('merges the adapters, newest first; same-time sessions keep the adapters’ order', async () => {
    const { sessions, errors } = await listAllSessions([fixed('a', [['a-old', 1], ['a-tie', 5]]), fixed('b', [['b-new', 9], ['b-tie', 5]])]);
    expect(sessions.map((s) => s.sessionId)).toEqual(['b-new', 'a-tie', 'b-tie', 'a-old']);
    expect(errors).toEqual([]);
  });

  it('a failing adapter is reported by name and does not take the others down — whatever it throws', async () => {
    const throwing: AgentAdapter = { agent: 'broken', listSessions: async () => Promise.reject(new Error('disk gone')) };
    const rejectsText: AgentAdapter = { agent: 'odd', listSessions: () => Promise.reject('just a string') };
    const { sessions, errors } = await listAllSessions([throwing, fixed('ok', [['x', 1]]), rejectsText]);
    expect(sessions.map((s) => s.sessionId)).toEqual(['x']);
    expect(errors.map((e) => [e.agent, e.error instanceof Error, e.error.message])).toEqual([
      ['broken', true, 'disk gone'],
      ['odd', true, 'just a string'],
    ]);
  });

  it('the real adapters together', async () => {
    const claude = createClaudeAdapter({ projectsDir: join(root, 'claude') });
    const { sessions, errors } = await listAllSessions([claude, { agent: 'broken', listSessions: () => Promise.reject(new Error('x')) }]);
    expect(sessions).toHaveLength(3);
    expect(errors.map((e) => e.agent)).toEqual(['broken']);
  });
});
